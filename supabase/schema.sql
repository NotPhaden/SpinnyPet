create or replace function public.beta_create_account(p_username text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
  uid uuid;
  token text := encode(gen_random_bytes(32), 'hex');
  clean text := trim(p_username);
begin
  if char_length(clean) < 3 or char_length(clean) > 20 then raise exception 'Username must be 3-20 characters'; end if;
  if clean !~ '^[A-Za-z0-9_]+$' then raise exception 'Username can contain only letters, numbers and _'; end if;
  if char_length(p_password) < 6 or char_length(p_password) > 72 then raise exception 'Password must be 6-72 characters'; end if;
  if exists(select 1 from beta_accounts where lower(username)=lower(clean)) then raise exception 'Username is already taken'; end if;

  insert into beta_accounts(username, password_hash) values(clean, crypt(p_password, gen_salt('bf'))) returning id into uid;
  insert into beta_sessions(token, user_id) values(token, uid);
  return jsonb_build_object('token', token, 'user_id', uid, 'username', clean, 'balance', 0);
end; $$;

create or replace function public.beta_login(p_username text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare
  a beta_accounts%rowtype;
  token text := encode(gen_random_bytes(32), 'hex');
begin
  select * into a from beta_accounts where lower(username)=lower(trim(p_username));
  if a.id is null or a.password_hash <> crypt(p_password, a.password_hash) then raise exception 'Invalid beta username or password'; end if;
  delete from beta_sessions where user_id=a.id and expires_at < now();
  insert into beta_sessions(token, user_id) values(token, a.id);
  return jsonb_build_object('token', token, 'user_id', a.id, 'username', a.username, 'balance', a.balance);
end; $$;

