returns integer language plpgsql security definer set search_path = public as $$
declare written integer;
begin
  if jsonb_typeof(rows) <> 'array' or jsonb_array_length(rows) > 5000 then raise exception 'Invalid rows payload'; end if;
  insert into public.pets_cache(id,name,category,thumbnail_asset,golden_thumbnail_asset,thumbnail_url,golden_thumbnail_url,rap,cosmic_value,exists_count,synced_at,updated_at)
  select x.id,x.name,coalesce(nullif(x.category,''),'Regular'),nullif(x.thumbnail_asset,''),nullif(x.golden_thumbnail_asset,''),nullif(x.thumbnail_url,''),nullif(x.golden_thumbnail_url,''),greatest(coalesce(x.rap,0),0),greatest(coalesce(x.cosmic_value,0),0),greatest(coalesce(x.exists_count,0),0),now(),now()
  from jsonb_to_recordset(rows) as x(id text,name text,category text,thumbnail_asset text,golden_thumbnail_asset text,thumbnail_url text,golden_thumbnail_url text,rap bigint,cosmic_value bigint,exists_count bigint)
  where nullif(x.id,'') is not null and nullif(x.name,'') is not null
  on conflict(id) do update set name=excluded.name,category=excluded.category,thumbnail_asset=coalesce(excluded.thumbnail_asset,pets_cache.thumbnail_asset),golden_thumbnail_asset=coalesce(excluded.golden_thumbnail_asset,pets_cache.golden_thumbnail_asset),thumbnail_url=coalesce(excluded.thumbnail_url,pets_cache.thumbnail_url),golden_thumbnail_url=coalesce(excluded.golden_thumbnail_url,pets_cache.golden_thumbnail_url),rap=excluded.rap,cosmic_value=case when excluded.cosmic_value>0 then excluded.cosmic_value else pets_cache.cosmic_value end,exists_count=excluded.exists_count,synced_at=now(),updated_at=now();
  get diagnostics written=row_count; return written;
end; $$;

